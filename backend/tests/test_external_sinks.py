"""Integration tests for the local Milestone 2 delivery sinks.

These tests exercise the real ``core.action_adapters`` code against real local
network listeners: a STARTTLS/AUTH SMTP server and an HTTPS webhook server.
No external provider is contacted and every credential is generated by the
test.
"""
from __future__ import annotations

import os
import shutil
import tempfile
import unittest
from pathlib import Path

import core.action_adapters as adapters
from core.company_operations import CompanyOperations
from core.office_store import OfficeStore
from tools.external_sinks import DeploySink, SmtpSink, ensure_test_certificates

OPENSSL = shutil.which("openssl")
ENV_KEYS = (
    "SMTP_HOST", "SMTP_PORT", "SMTP_USERNAME", "SMTP_PASSWORD", "SMTP_FROM",
    "DEPLOY_WEBHOOK_URL", "DEPLOY_WEBHOOK_TOKEN", "SSL_CERT_FILE",
    "OUTBOX_MAX_ATTEMPTS", "OUTBOX_BACKOFF_SECONDS", "OUTBOX_BACKOFF_MAX_SECONDS",
)


@unittest.skipUnless(OPENSSL, "openssl is required to generate test certificates")
class ExternalSinkAdapterTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls._cert_root = tempfile.TemporaryDirectory(prefix="m2-certs-")
        cls.certs = ensure_test_certificates(Path(cls._cert_root.name) / "certs")

    @classmethod
    def tearDownClass(cls):
        cls._cert_root.cleanup()

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="m2-sinks-")
        self.root = Path(self.tmp.name)
        self.ops = CompanyOperations(OfficeStore(self.root / "office.db"))
        self._original_ops = adapters.OPS
        adapters.OPS = self.ops
        self._saved_env = {key: os.environ.get(key) for key in ENV_KEYS}
        for key in ENV_KEYS:
            os.environ.pop(key, None)
        os.environ["SSL_CERT_FILE"] = self.certs["ca_file"]
        self._sinks = []

    def tearDown(self):
        for sink in self._sinks:
            sink.stop()
        adapters.OPS = self._original_ops
        for key, value in self._saved_env.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
        self.tmp.cleanup()

    def _smtp_sink(self, **kwargs):
        sink = SmtpSink(
            self.certs["cert_file"], self.certs["key_file"],
            self.root / f"smtp-{len(self._sinks)}.jsonl",
            "milestone2", kwargs.pop("password", "smtp-secret"), **kwargs,
        )
        self._sinks.append(sink)
        return sink

    def _deploy_sink(self, token="deploy-secret"):
        sink = DeploySink(
            self.certs["cert_file"], self.certs["key_file"],
            self.root / "deploy.jsonl", token,
        )
        self._sinks.append(sink)
        return sink

    def _approved_outbox(self, action_type, payload):
        approval = self.ops.create_approval(
            action_type, "Sink integration test", payload,
            actor="owner", actor_role="owner",
        )
        self.ops.decide_approval(approval["id"], "approve", "owner", "approved")
        return next(
            item["id"] for item in self.ops.list_outbox()
            if item["approval_id"] == approval["id"]
        )

    def test_smtp_sink_starttls_auth_delivery_and_idempotency(self):
        sink = self._smtp_sink()
        os.environ.update({
            "SMTP_HOST": "127.0.0.1",
            "SMTP_PORT": str(sink.port),
            "SMTP_USERNAME": "milestone2",
            "SMTP_PASSWORD": "smtp-secret",
            "SMTP_FROM": "company@example.test",
        })
        outbox_id = self._approved_outbox("email.send", {
            "to": "owner@example.test",
            "subject": "Sink integration",
            "body": "Body from the real adapter.",
        })
        result = adapters.execute_outbox(outbox_id)
        self.assertTrue(result["success"])
        self.assertEqual(result["result"]["provider"], "smtp")
        records = sink.log.records()
        self.assertEqual(len(records), 1)
        self.assertEqual(records[0]["outbox_id"], outbox_id)
        self.assertEqual(records[0]["authenticated_user"], "milestone2")
        self.assertEqual(records[0]["subject"], "Sink integration")
        self.assertIn("Body from the real adapter.", records[0]["body"])

        duplicate = adapters.execute_outbox(outbox_id)
        self.assertTrue(duplicate["already_completed"])
        self.assertEqual(len(sink.log.records()), 1)

    def test_deploy_sink_https_delivery_and_idempotency(self):
        sink = self._deploy_sink()
        os.environ.update({
            "DEPLOY_WEBHOOK_URL": f"https://127.0.0.1:{sink.port}/hook",
            "DEPLOY_WEBHOOK_TOKEN": "deploy-secret",
        })
        outbox_id = self._approved_outbox("website.deploy", {
            "repository": "https://example.test/site.git",
            "ref": "main",
            "target": "staging",
        })
        result = adapters.execute_outbox(outbox_id)
        self.assertTrue(result["success"])
        self.assertEqual(result["result"]["provider"], "deployment_webhook")
        records = sink.log.records()
        self.assertEqual(len(records), 1)
        self.assertEqual(records[0]["body"]["outbox_id"], outbox_id)
        self.assertEqual(records[0]["idempotency_key"], outbox_id)
        self.assertEqual(result["result"]["external_id"], records[0]["deployment_id"])

        duplicate = adapters.execute_outbox(outbox_id)
        self.assertTrue(duplicate["already_completed"])
        self.assertEqual(len(sink.log.records()), 1)

    def test_drop_after_data_marks_outbox_unknown(self):
        sink = self._smtp_sink(drop_after_data=True)
        os.environ.update({
            "SMTP_HOST": "127.0.0.1",
            "SMTP_PORT": str(sink.port),
            "SMTP_USERNAME": "milestone2",
            "SMTP_PASSWORD": "smtp-secret",
            "SMTP_FROM": "company@example.test",
        })
        outbox_id = self._approved_outbox("email.send", {
            "to": "owner@example.test",
            "subject": "Unknown delivery",
            "body": "The sink received this but never acknowledged it.",
        })
        with self.assertRaises(adapters.AdapterError):
            adapters.execute_outbox(outbox_id)
        row = next(item for item in self.ops.list_outbox() if item["id"] == outbox_id)
        self.assertEqual(row["status"], "unknown")
        self.assertEqual(len(sink.log.records()), 1)
        with self.assertRaises(adapters.AdapterError):
            adapters.execute_outbox(outbox_id)
        self.assertEqual(len(sink.log.records()), 1)

        resolved = self.ops.reconcile_outbox(
            outbox_id, "succeeded", "Sink log confirms one message.",
            external_id=sink.log.records()[0]["message_id"], actor="owner",
        )
        self.assertEqual(resolved["status"], "succeeded")
        self.assertEqual(resolved["resolved_by"], "owner")

    def test_rejected_smtp_auth_exhausts_without_delivery(self):
        sink = self._smtp_sink(password="a-different-password")
        os.environ.update({
            "SMTP_HOST": "127.0.0.1",
            "SMTP_PORT": str(sink.port),
            "SMTP_USERNAME": "milestone2",
            "SMTP_PASSWORD": "smtp-secret",
            "SMTP_FROM": "company@example.test",
            "OUTBOX_MAX_ATTEMPTS": "1",
        })
        outbox_id = self._approved_outbox("email.send", {
            "to": "owner@example.test",
            "subject": "Rejected auth",
            "body": "Never delivered.",
        })
        with self.assertRaises(adapters.AdapterError):
            adapters.execute_outbox(outbox_id)
        row = next(item for item in self.ops.list_outbox() if item["id"] == outbox_id)
        self.assertEqual(row["status"], "failed")
        self.assertEqual(row["attempts"], 1)
        self.assertIsNone(row["next_retry_at"])
        self.assertEqual(sink.log.records(), [])
        with self.assertRaises(adapters.AdapterError):
            adapters.execute_outbox(outbox_id)
        self.assertEqual(sink.log.records(), [])

        requeued = self.ops.requeue_outbox(outbox_id, actor="owner")
        self.assertEqual(requeued["status"], "queued")
        self.assertEqual(requeued["attempts"], 0)

    def test_plain_http_deploy_webhook_is_rejected_before_connecting(self):
        os.environ.update({
            "DEPLOY_WEBHOOK_URL": "http://127.0.0.1:9/hook",
            "DEPLOY_WEBHOOK_TOKEN": "deploy-secret",
        })
        outbox_id = self._approved_outbox("website.deploy", {
            "repository": "https://example.test/site.git",
            "ref": "main",
            "target": "staging",
        })
        with self.assertRaises(adapters.AdapterError):
            adapters.execute_outbox(outbox_id)
        row = next(item for item in self.ops.list_outbox() if item["id"] == outbox_id)
        self.assertEqual(row["status"], "failed")
        self.assertIn("HTTPS", row["last_error"])


if __name__ == "__main__":
    unittest.main()
